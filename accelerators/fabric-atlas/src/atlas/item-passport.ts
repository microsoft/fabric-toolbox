import { buildGovernanceFindings, type GovernanceFinding, type GovernanceSeverity } from "./governance";
import { typeMeta, type AtlasData, type Item } from "./model";

export type ItemPassportData = Pick<
  AtlasData,
  "workspace" | "items" | "principals" | "grants" | "jobs" | "edges"
> &
  Partial<Pick<AtlasData, "schema" | "governanceEvidence">>;

const SEVERITY_ORDER: Record<GovernanceSeverity, number> = { critical: 0, high: 1, medium: 2, low: 3 };
const RECENT_JOBS = 5;

/** Governance findings that target one item, most severe first. */
export function itemFindings(findings: readonly GovernanceFinding[], itemId: string): GovernanceFinding[] {
  return findings
    .filter((finding) => finding.itemId === itemId || finding.target?.itemId === itemId)
    .sort((a, b) => SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity]);
}

function ownerLine(item: Item): string {
  if (item.ownerName) return item.ownerEmail ? `${item.ownerName} (${item.ownerEmail})` : item.ownerName;
  if (item.ownerEmail) return item.ownerEmail;
  return item.ownerMetadataAvailable === false ? "Not collected" : "Unassigned";
}

function sensitivityLine(item: Item): string {
  if (item.sensitivity) return item.sensitivity;
  if (item.sensitivityLabelId) return "Label applied";
  return item.sensitivityMetadataAvailable === false ? "Not collected" : "Unlabeled";
}

function endorsementLine(item: Item): string {
  if (item.endorsementMetadataAvailable === false && !item.endorsementRaw) return "Not collected";
  const value = item.endorsementRaw ?? item.endorsement;
  return item.endorsementBy ? `${value} (by ${item.endorsementBy})` : value;
}

function tagsLine(item: Item): string {
  if (item.tags.length) return item.tags.join(", ");
  if (item.tagIds?.length) return `${item.tagIds.length} tag(s), names not resolved`;
  return item.tagMetadataAvailable === false ? "Not collected" : "None";
}

function cell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

/**
 * One-page Markdown identity sheet for a Fabric item. Missing evidence is written as
 * "Not collected" or "None recorded", never as zero.
 */
export function itemPassportMarkdown(
  data: ItemPassportData,
  itemId: string,
  options: { generatedAt?: string; findings?: readonly GovernanceFinding[] } = {},
): string | null {
  const item = data.items.find((entry) => entry.fabricId === itemId);
  if (!item) return null;
  const byId = new Map(data.items.map((entry) => [entry.fabricId, entry]));
  const upstream = data.edges.filter((edge) => edge.target === itemId);
  const downstream = data.edges.filter((edge) => edge.source === itemId);
  const grants = data.grants.filter((grant) => grant.itemFabricId === itemId);
  const jobs = data.jobs
    .filter((job) => job.itemFabricId === itemId)
    .sort((a, b) => b.startedAt.localeCompare(a.startedAt))
    .slice(0, RECENT_JOBS);
  const findings = itemFindings(options.findings ?? buildGovernanceFindings(data), itemId);
  const principalName = (ref: string) =>
    data.principals.find((p) => p.principalId === ref || p.email === ref || p.displayName === ref)?.displayName ?? ref;

  const lines: string[] = [`# ${item.displayName} — identity sheet`, ""];
  lines.push(
    `Generated by Fabric Atlas${options.generatedAt ? ` on ${options.generatedAt}` : ""} from the last synced snapshot${
      data.workspace.syncedAt ? ` (${data.workspace.syncedAt})` : ""
    }.`,
    "",
  );

  lines.push("## Identity", "");
  lines.push(`- Name: ${item.displayName}`);
  lines.push(`- Type: ${typeMeta(item.itemType).label}`);
  lines.push(`- Fabric ID: \`${item.fabricId}\``);
  lines.push(`- Workspace: ${data.workspace.displayName}`);
  lines.push(`- Description: ${item.description?.trim() || "None"}`);
  lines.push("");

  lines.push("## Ownership", "");
  lines.push(`- Documented owner: ${ownerLine(item)}`);
  lines.push(`- Configured by: ${item.configuredBy ?? "Not collected"}`);
  lines.push(`- Modified by: ${item.modifiedBy ?? "Not collected"}`);
  lines.push("");

  lines.push("## Trust", "");
  lines.push(`- Health: ${item.health}`);
  lines.push(`- Endorsement: ${endorsementLine(item)}`);
  lines.push(`- Sensitivity: ${sensitivityLine(item)}`);
  lines.push(`- Tags: ${tagsLine(item)}`);
  lines.push(`- Last refresh: ${item.lastRefresh ?? "None recorded"}`);
  lines.push("");

  lines.push(`## Lineage (${upstream.length} upstream · ${downstream.length} downstream)`, "");
  if (!upstream.length && !downstream.length) {
    lines.push("None recorded.", "");
  } else {
    lines.push("| Direction | Item | Type | Relation |", "| --- | --- | --- | --- |");
    for (const [direction, edges, key] of [
      ["Upstream", upstream, "source"],
      ["Downstream", downstream, "target"],
    ] as const) {
      for (const edge of edges) {
        const other = byId.get(edge[key]);
        lines.push(
          `| ${direction} | ${cell(other?.displayName ?? edge[key])} | ${other ? typeMeta(other.itemType).label : "External"} | ${cell(edge.relation)}${edge.broken ? " (broken)" : ""} |`,
        );
      }
    }
    lines.push("");
  }

  lines.push(`## Access (${grants.length} item grants)`, "");
  if (!grants.length) {
    lines.push("No item-level grants recorded. Workspace roles still apply.", "");
  } else {
    lines.push("| Principal | Access | Source |", "| --- | --- | --- |");
    for (const grant of grants) {
      lines.push(
        `| ${cell(principalName(grant.principalRef))} | ${cell(grant.roleName ?? grant.accessLevel)}${grant.flag ? ` (${grant.flag})` : ""} | ${grant.source} |`,
      );
    }
    lines.push("");
  }

  lines.push(`## Governance findings (${findings.length})`, "");
  if (!findings.length) {
    lines.push("No findings target this item.", "");
  } else {
    for (const finding of findings) {
      lines.push(`- **${finding.severity.toUpperCase()}** — ${finding.title}. ${finding.recommendation}`);
    }
    lines.push("");
  }

  lines.push("## Recent jobs", "");
  if (!jobs.length) {
    lines.push("None recorded.", "");
  } else {
    lines.push("| Started | Job | Status | Duration |", "| --- | --- | --- | --- |");
    for (const job of jobs) {
      lines.push(`| ${job.startedAt} | ${cell(job.jobType)} | ${job.status} | ${job.durationSec}s |`);
    }
    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

/** Question sent to Atlas Scout when the user asks about one item. */
export function scoutItemQuestion(item: Pick<Item, "displayName" | "itemType" | "fabricId">): string {
  return `Tell me about the ${typeMeta(item.itemType).label} "${item.displayName}" (Fabric ID ${item.fabricId}): owner, health, upstream and downstream impact, access and open governance findings.`;
}
